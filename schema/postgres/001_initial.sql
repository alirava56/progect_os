CREATE TABLE users (
  id TEXT PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  display_name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  salt TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  failed_logins INTEGER NOT NULL DEFAULT 0,
  locked_until BIGINT NOT NULL DEFAULT 0,
  mfa_seed TEXT,
  mfa_pending TEXT,
  mfa_pending_session TEXT,
  mfa_pending_until BIGINT NOT NULL DEFAULT 0,
  mfa_last_step BIGINT NOT NULL DEFAULT -1,
  mfa_failed INTEGER NOT NULL DEFAULT 0,
  mfa_locked_until BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE workspaces (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
  created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE memberships (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('owner', 'editor', 'viewer')),
  project_ids TEXT,
  PRIMARY KEY (user_id, workspace_id),
  UNIQUE (user_id),
  CHECK (role <> 'owner' OR project_ids IS NULL)
);
CREATE INDEX memberships_by_workspace ON memberships(workspace_id);
CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES memberships(user_id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  last_seen_at BIGINT NOT NULL
);
CREATE INDEX idx_sessions_expiry ON sessions(expires_at);
CREATE INDEX sessions_by_user ON sessions(user_id);
CREATE TABLE records (
  workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('projects', 'tasks', 'resources', 'secrets', 'reminders', 'incidents',
    'expenses', 'charges', 'contracts', 'revenues', 'docs', 'preferences')),
  id TEXT NOT NULL,
  project_id TEXT,
  project_kind TEXT GENERATED ALWAYS AS ('projects'::text) STORED,
  payload TEXT NOT NULL CHECK (jsonb_typeof(payload::jsonb) = 'object'),
  updated_at TIMESTAMPTZ NOT NULL,
  record_version BIGINT NOT NULL DEFAULT 0 CHECK (record_version >= 0),
  PRIMARY KEY (workspace_id, kind, id),
  FOREIGN KEY (workspace_id, project_kind, project_id)
    REFERENCES records(workspace_id, kind, id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX idx_records_project ON records(workspace_id, project_id);
CREATE TABLE record_tombstones (
  workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  id TEXT NOT NULL,
  record_version BIGINT NOT NULL,
  PRIMARY KEY (workspace_id, kind, id)
);
CREATE TABLE audit_events (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  actor_id TEXT NOT NULL REFERENCES users(id),
  kind TEXT NOT NULL,
  record_id TEXT NOT NULL,
  action TEXT NOT NULL,
  title TEXT NOT NULL,
  project_id TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL,
  actor_snapshot TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_audit_ws_date ON audit_events(workspace_id, created_at DESC);
CREATE TABLE document_versions (
  workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  document_id TEXT NOT NULL,
  revision INTEGER NOT NULL,
  payload TEXT NOT NULL CHECK (jsonb_typeof(payload::jsonb) = 'object'),
  saved_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (workspace_id, document_id, revision)
);
CREATE TABLE workspace_invites (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('editor', 'viewer')),
  token_hash TEXT NOT NULL UNIQUE,
  expires_at BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  redeemed_at BIGINT,
  revoked_at BIGINT,
  project_ids TEXT
);
CREATE INDEX idx_invites_workspace ON workspace_invites(workspace_id, created_at DESC);
CREATE TABLE mfa_recovery_codes (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (user_id, code_hash)
);
CREATE TABLE notification_outbox (
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  reminder_id TEXT NOT NULL,
  scheduled_for TEXT NOT NULL,
  channel TEXT NOT NULL,
  state TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  delivered_at TIMESTAMPTZ,
  UNIQUE (workspace_id, reminder_id, scheduled_for, channel)
);
CREATE INDEX outbox_by_channel ON notification_outbox(channel, state, created_at);
CREATE TABLE delivery_retries (
  notification_id TEXT PRIMARY KEY,
  attempts INTEGER NOT NULL DEFAULT 0,
  retry_after BIGINT NOT NULL DEFAULT 0,
  claimed_at BIGINT NOT NULL DEFAULT 0,
  lease_token TEXT
);
CREATE TABLE monitor_observations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  resource_id TEXT NOT NULL,
  checked_at TIMESTAMPTZ NOT NULL,
  state TEXT NOT NULL,
  status_code INTEGER,
  latency_ms INTEGER,
  diagnostic TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'https',
  UNIQUE(workspace_id, resource_id, checked_at)
);
CREATE INDEX idx_observation_latest ON monitor_observations(workspace_id, resource_id, checked_at DESC);
CREATE TABLE ai_quota (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  hourly_window TEXT NOT NULL,
  used INTEGER NOT NULL,
  PRIMARY KEY (user_id, hourly_window)
);
CREATE TABLE auth_rate_limits (
  scope TEXT NOT NULL,
  bucket TEXT NOT NULL,
  expires_at BIGINT NOT NULL,
  hits INTEGER NOT NULL,
  PRIMARY KEY (scope, bucket)
);
CREATE INDEX auth_rate_limits_expiry ON auth_rate_limits(expires_at);
CREATE TABLE worker_heartbeats (
  name TEXT PRIMARY KEY,
  checked_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE sqlite_imports (
  source_digest TEXT PRIMARY KEY,
  manifest TEXT NOT NULL,
  imported_at TIMESTAMPTZ NOT NULL
);